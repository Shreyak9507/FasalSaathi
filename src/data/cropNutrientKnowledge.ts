/**
 * Helper to safely retrieve a crop's nutrient profile.
 * Returns null if the crop is not recognized in the knowledge base.
 */
export function getCropNutrientProfile(cropId: string): CropNutrientProfile | null {
  if (!cropId) return null;
  const cleanId = cropId.toLowerCase().trim();
  return CROP_NUTRIENT_KNOWLEDGE[cleanId] || null;
}
